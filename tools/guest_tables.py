#!/usr/bin/env python3
"""Guest table layout: reads config/guest_tables.toml, places each table at the end of its own pages with a guard
page before the next, and writes src/common/guest_tables_layout.h (the host maps and checks it at start-up).

  python3 -I tools/guest_tables.py            write the header
  python3 -I tools/guest_tables.py --check    fail when the header does not match the config
  python3 -I tools/guest_tables.py --print    the layout as text
  --config FILE --header FILE                 other paths (tests)
"""
import argparse, os, sys, tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGE = 0x1000
USER_HIGH = 0x7FFE0000  # the guest user range ends here (sdk/runtime/kernel/memory.h kUserHigh)


class LayoutError(Exception):
    pass


def layout(cfg):
    """[(name, va, elem, count, align, what)] for the config's region; raises LayoutError with the reason"""
    reg = cfg.get('region', {})
    base, size = reg.get('base'), reg.get('size')
    if base is None or size is None:
        raise LayoutError('[region] needs base and size')
    if base % 0x10000 or size % 0x10000 or size <= 0:
        raise LayoutError('the region must start and end on 64 KB boundaries (the guest allocator\'s granularity)')
    if base < 0x10000 or base + size > USER_HIGH:
        raise LayoutError('the region must lie in the guest user range 0x10000..0x%X' % USER_HIGH)
    out, names = [], set()
    cursor = base + PAGE  # a guard page before the first table
    for t in cfg.get('table', []):
        name, elem, count, align = t.get('name'), t.get('elem'), t.get('count'), t.get('align', 4)
        if not name or not name.isidentifier():
            raise LayoutError('table name %r is not an identifier' % name)
        if name in names:
            raise LayoutError('two tables named %s' % name)
        names.add(name)
        if not isinstance(elem, int) or not isinstance(count, int) or elem <= 0 or count <= 0:
            raise LayoutError('%s: elem and count must be positive' % name)
        if align <= 0 or align & (align - 1) or align > PAGE:
            raise LayoutError('%s: align must be a power of two up to the page size' % name)
        if elem % align:
            raise LayoutError('%s: elem 0x%X is not a multiple of align %d (the table would not end at its guard page)'
                              % (name, elem, align))
        total = elem * count
        end = cursor + (total + PAGE - 1) // PAGE * PAGE
        va = end - total  # ends exactly at the guard page: elem is a multiple of align, so va is aligned too
        if end + PAGE > base + size:
            raise LayoutError('%s: the region is full (0x%X bytes needed past 0x%X)' % (name, total, base + size))
        text = t.get('text')
        if text is not None and (not isinstance(text, str) or len(text.encode()) + 1 > total):
            raise LayoutError('%s: its text needs %d bytes, the table has %d' % (name, len(str(text).encode()) + 1, total))
        out.append((name, va, elem, count, align, t.get('what', '')))
        cursor = end + PAGE
    return out


def header(cfg, tables):
    reg = cfg['region']
    lines = ['// Generated by tools/guest_tables.py from config/guest_tables.toml: do not edit.',
             '#pragma once', '#include "common/guest_tables.h"', '',
             'namespace guest_tables {', '',
             'constexpr Region kRegion = {0x%08Xu, 0x%08Xu};' % (reg['base'], reg['size']), '']
    if tables:
        lines.append('constexpr Table kTables[] = {')
        for name, va, elem, count, align, what in tables:
            lines.append('    {"%s", 0x%08Xu, 0x%Xu, %du, %du},  // %s' % (name, va, elem, count, align, what))
        lines.append('};')
        lines.append('constexpr size_t kTableCount = sizeof(kTables) / sizeof(kTables[0]);')
        lines.append('')
        lines.append('// each table by name, for host code: kTables[k_NAME]')
        for k, (name, va, elem, count, align, what) in enumerate(tables):
            lines.append('constexpr size_t k_%s = %d;' % (name, k))
        texts = [(k, t['text']) for k, t in enumerate(cfg.get('table', [])) if 'text' in t]
        lines.append('')
        lines.append('// tables that start with a text (a NUL-terminated string the recompiled code is pointed at)')
        if texts:
            lines.append('constexpr TableText kTexts[] = {')
            for k, text in texts:
                lines.append('    {%d, %s},' % (k, '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'))
            lines.append('};')
            lines.append('constexpr size_t kTextCount = sizeof(kTexts) / sizeof(kTexts[0]);')
        else:
            lines.append('constexpr const TableText* kTexts = nullptr;')
            lines.append('constexpr size_t kTextCount = 0;')
    else:
        lines.append('constexpr const Table* kTables = nullptr;  // none yet')
        lines.append('constexpr size_t kTableCount = 0;')
        lines.append('constexpr const TableText* kTexts = nullptr;')
        lines.append('constexpr size_t kTextCount = 0;')
    lines += ['', '}  // namespace guest_tables', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--config', default=os.path.join(ROOT, 'config', 'guest_tables.toml'))
    ap.add_argument('--header', default=os.path.join(ROOT, 'src', 'common', 'guest_tables_layout.h'))
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--print', action='store_true')
    a = ap.parse_args()
    cfg = tomllib.load(open(a.config, 'rb'))
    try:
        tables = layout(cfg)
    except LayoutError as e:
        print('%s: %s' % (os.path.basename(a.config), e))
        return 1
    if a.print:
        for name, va, elem, count, align, what in tables:
            print('%-28s %08X..%08X  %d x 0x%X (align %d)  %s' % (name, va, va + elem * count, count, elem, align, what))
    text = header(cfg, tables)
    if a.check:
        cur = open(a.header).read() if os.path.exists(a.header) else ''
        if cur != text:
            print('%s does not match %s: run tools/guest_tables.py' % (a.header, a.config))
            return 1
        return 0
    if not a.print:
        open(a.header, 'w').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
